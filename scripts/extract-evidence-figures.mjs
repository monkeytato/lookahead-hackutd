// Copies the 8 charts from the Prediction Science brief into the landing page.
//   node docs/pdf-src/build.mjs                (regenerates the brief and its charts)
//   node scripts/extract-evidence-figures.mjs  (writes src/landing/evidenceFigures.ts)
// The charts are not redrawn: each SVG is taken as-is from the brief, with ids namespaced so markers never collide.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const html = readFileSync(resolve(ROOT, 'docs/pdf-src/CenterGuard-Prediction-Science.html'), 'utf8');
const figs = [...html.matchAll(/<figure[\s\S]*?<\/figure>/g)].map((m) => m[0]);
if (figs.length !== 8) throw new Error(`expected 8 figures, found ${figs.length}`);

const decode = (t) => t.replace(/&amp;/g, '&').replace(/&lt;/g, '<').replace(/&gt;/g, '>').replace(/&quot;/g, '"').replace(/&#39;/g, "'");
const out = figs.map((fig, i) => {
  const n = i + 1;
  let svg = fig.match(/<svg[\s\S]*<\/svg>/)[0];
  for (const id of new Set([...svg.matchAll(/id="([^"]+)"/g)].map((m) => m[1]))) {
    svg = svg.replaceAll(`id="${id}"`, `id="ev${n}-${id}"`).replaceAll(`url(#${id})`, `url(#ev${n}-${id})`);
  }
  svg = svg.replace(/\swidth="100%"/, '');
  const caption = decode((fig.match(/<figcaption>([\s\S]*?)<\/figcaption>/)?.[1] ?? '').replace(/<[^>]+>/g, '').replace(/^\s*Figure \d+\.\s*/, '').replace(/\s+/g, ' ').trim());
  return { n, svg, caption };
});

const ts = `// Generated by scripts/extract-evidence-figures.mjs from docs/pdf-src/CenterGuard-Prediction-Science.html. Do not edit by hand.
export interface EvidenceFigure { n: number; svg: string; caption: string }
export const EVIDENCE_FIGURES: EvidenceFigure[] = ${JSON.stringify(out, null, 1)};
`;
writeFileSync(resolve(ROOT, 'src/landing/evidenceFigures.ts'), ts);
console.log('wrote src/landing/evidenceFigures.ts', out.map((f) => `fig${f.n} ${f.svg.length}B`).join(', '));
